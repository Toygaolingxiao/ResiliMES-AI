"""Build the kernel tables from the public SMT2020 LV/HM files.

Source: Kopp, Hassoun, Kalir, Mönch, IEEE Trans. Semicond. Manuf. 33(4), 2020,
doi 10.1109/TSM.2020.3001933. Files from PySCFabSim-release commit 0dbff6a,
``datasets/SMT2020_LVHM``. The paper says the dataset is open to public use.

Standard cycle time is the published PTIME mean, in seconds. ``per_piece`` is
multiplied by the published lot size of 25. ``per_batch`` is the furnace cycle
and is not divided. ``RPT#`` is not a demand quantity. Customers, margin tiers,
and the DPI weights are derived and labeled. ``ped_remaining_sec`` is null:
WIP has no step-start timestamp.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from resilimes.kernel.score import dynamic_priority, order_class_from_priority

SNAPSHOT = datetime(2018, 1, 1, tzinfo=UTC)
PIECES = 25
_PROVENANCE = (
    "smt2020; order_class derived from PRIOR (HOTLOT column is no); "
    "customer derived from the order id; margin_tier unpriced; "
    "dpi computed at 2018-01-01 from published mean process times"
)


@dataclass(frozen=True)
class OperationRow:
    op_id: str
    recipe_id: str
    station_group_id: str
    std_cycle_time: float
    max_ped_sec: float | None
    requires_batch: bool
    batch_size: int | None
    ped_target_op_id: str
    route_id: str
    step_no: int


@dataclass(frozen=True)
class SetupRow:
    station_group_id: str
    from_recipe: str
    to_recipe: str
    setup_time_sec: float


@dataclass(frozen=True)
class OrderRow:
    order_id: str
    customer: str
    product_id: str
    qty: int
    contract_due: datetime
    order_class: str
    margin_tier: str
    release_interval_min: float
    priority: int


@dataclass(frozen=True)
class LotRow:
    lot_id: str
    product_id: str
    current_op_id: str
    priority_level: int
    arrival_time: datetime
    due_date: datetime
    ped_remaining_sec: float | None
    dpi: float
    dpi_updated_at: datetime
    late: bool
    order_class: str
    lot_value: float


@dataclass(frozen=True)
class PmRow:
    cal_name: str
    family: str
    first_start_sec: float
    interval_sec: float
    duration_sec: float


@dataclass
class KernelTables:
    operations: list[OperationRow]
    setups: list[SetupRow]
    orders: list[OrderRow]
    lots: list[LotRow]
    pm_calendar: list[PmRow]
    routes: dict[str, list[str]]
    scanner_families: dict[str, int]


def load_tables(root: Path) -> KernelTables:
    parts = _parts(root / "part.txt")
    routes = _routes(root, parts)
    operations = [step for steps in routes.values() for step in steps]
    by_route: dict[str, list[OperationRow]] = {}
    for step in operations:
        by_route.setdefault(step.route_id, []).append(step)
    for steps in by_route.values():
        steps.sort(key=lambda item: item.step_no)
    route_index = {route_id: [step.op_id for step in steps] for route_id, steps in by_route.items()}
    return KernelTables(
        operations=operations,
        setups=_setups(root),
        orders=_orders(root / "order.txt"),
        lots=_lots(root / "WIP.txt", parts, by_route),
        pm_calendar=_pm(root),
        routes=route_index,
        scanner_families=_scanners(root / "tool.txt.1l"),
    )


def render_sql(tables: KernelTables) -> str:
    """Typed Postgres DDL and inserts. Schema name is ``resilimes`` in every database."""
    lines = [
        "-- SMT2020 kernel tables. Generated by resilimes.data.smt2020_kernel.",
        "-- Citation: Kopp, Hassoun, Kalir, Moench, IEEE TSM 33(4) 2020,",
        "-- doi 10.1109/TSM.2020.3001933. PySCFabSim-release commit 0dbff6a.",
        "-- Cycle times are published PTIME means in seconds, not random draws.",
        "-- Customers, margin tiers, order class, and DPI are derived.",
        "-- The setup script routes each table to fab_mes, fab_cmms, or fab_erp.",
        _create_operations(),
        *_insert_operations(tables.operations),
        _create_setup(),
        *_insert_setups(tables.setups),
        _create_orders(),
        *_insert_orders(tables.orders),
        _create_lots(),
        *_insert_lots(tables.lots),
        _create_pm(),
        *_insert_pm(tables.pm_calendar),
        "",
    ]
    return "\n".join(lines)


def _parts(path: Path) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for row in _rows(path):
        mapping[row["PART"]] = row["ROUTE"]
    return mapping


def _routes(root: Path, parts: dict[str, str]) -> dict[str, list[OperationRow]]:
    del parts
    files: dict[str, Path] = {}
    for row in _rows(root / "part.txt"):
        files[row["ROUTE"]] = root / row["ROUTEFILE"]
    built: dict[str, list[OperationRow]] = {}
    for route_id, path in files.items():
        steps = list(_rows(path))
        by_number = {int(step["STEP"]): step for step in steps}
        parsed: list[OperationRow] = []
        for step in steps:
            number = int(step["STEP"])
            target = ""
            ped: float | None = None
            if step["CQT"].strip():
                ped = _to_sec(float(step["CQT"]), step["CQTUNITS"] or "hr")
                target_no = step["STEP_CQT"].strip()
                if target_no and int(float(target_no)) in by_number:
                    target = f"{route_id}:{int(float(target_no))}"
            parsed.append(
                OperationRow(
                    op_id=f"{route_id}:{number}",
                    recipe_id=(step["SETUP"].strip() or step["DESC"].strip() or f"step-{number}"),
                    station_group_id=step["STNFAM"].strip(),
                    std_cycle_time=_cycle_sec(step),
                    max_ped_sec=ped,
                    requires_batch=step["PTPER"].strip() == "per_batch",
                    batch_size=int(float(step["BATCHMX"])) if step["BATCHMX"].strip() else None,
                    ped_target_op_id=target,
                    route_id=route_id,
                    step_no=number,
                )
            )
        built[route_id] = parsed
    return built


def _setups(root: Path) -> list[SetupRow]:
    rows: list[SetupRow] = []
    seen: set[tuple[str, str, str]] = set()
    for row in _rows(root / "setup.txt"):
        group = row["IGNORE"].strip()
        item = SetupRow(
            station_group_id=group,
            from_recipe=row["CURSETUP"].strip(),
            to_recipe=row["NEWSETUP"].strip(),
            setup_time_sec=_to_sec(float(row["STIME"]), row["STUNITS"] or "min"),
        )
        seen.add((item.station_group_id, item.from_recipe, item.to_recipe))
        rows.append(item)
    for raw in _route_setup_edges(root):
        key = (raw.station_group_id, raw.from_recipe, raw.to_recipe)
        if key in seen or not raw.to_recipe:
            continue
        seen.add(key)
        rows.append(raw)
    return rows


def _route_setup_edges(root: Path) -> list[SetupRow]:
    edges: list[SetupRow] = []
    for row in _rows(root / "part.txt"):
        for step in _rows(root / row["ROUTEFILE"]):
            setup = step["SETUP"].strip()
            stime = step["STIME"].strip()
            if not setup or not stime:
                continue
            edges.append(
                SetupRow(
                    station_group_id=step["STNFAM"].strip(),
                    from_recipe="",
                    to_recipe=setup,
                    setup_time_sec=_to_sec(float(stime), step["STUNITS"] or "min"),
                )
            )
    return edges


def _orders(path: Path) -> list[OrderRow]:
    orders: list[OrderRow] = []
    for row in _rows(path):
        priority = int(float(row["PRIOR"]))
        orders.append(
            OrderRow(
                order_id=row["ORDER"].strip(),
                customer=f"derived:{row['ORDER'].strip()}",
                product_id=row["PART"].strip(),
                qty=int(float(row["PIECES"])),
                contract_due=_stamp(row["DUE"]),
                order_class=order_class_from_priority(priority),
                margin_tier="unpriced",
                release_interval_min=float(row["REPEAT"]),
                priority=priority,
            )
        )
    return orders


def _lots(
    path: Path,
    parts: dict[str, str],
    routes: dict[str, list[OperationRow]],
) -> list[LotRow]:
    lots: list[LotRow] = []
    for row in _rows(path):
        route_id = parts[row["PART"].strip()]
        steps = routes[route_id]
        current = int(float(row["CURSTEP"]))
        remaining = _remaining(steps, current)
        op_id = f"{route_id}:{current}"
        priority = int(float(row["PRIOR"]))
        kind = order_class_from_priority(priority)
        due = _stamp(row["DUE"])
        arrival = _stamp(row["START"])
        index = dynamic_priority(
            due_sec=(due - SNAPSHOT).total_seconds(),
            now_sec=0.0,
            remaining_sec=remaining,
            order_class=kind,
            margin_tier="unpriced",
        )
        lots.append(
            LotRow(
                lot_id=row["LOT"].strip(),
                product_id=row["PART"].strip(),
                current_op_id=op_id,
                priority_level=priority,
                arrival_time=arrival,
                due_date=due,
                ped_remaining_sec=None,
                dpi=index.index,
                dpi_updated_at=SNAPSHOT,
                late=index.late,
                order_class=kind,
                lot_value=index.lot_value,
            )
        )
    return lots


def _remaining(steps: list[OperationRow], current: int) -> float:
    total = 0.0
    started = False
    for step in steps:
        if step.step_no == current:
            started = True
        if started:
            total += step.std_cycle_time
    if not started:
        raise ValueError(f"Step {current} is not on the route")
    return total


def _pm(root: Path) -> list[PmRow]:
    attach = {row["CALNAME"]: row for row in _rows(root / "attach.txt")}
    calendar: list[PmRow] = []
    for row in _rows(root / "pmcal.txt"):
        linked = attach.get(row["PMCALNAME"])
        if linked is None or linked["CALTYPE"].strip() != "pm":
            continue
        # Piece counters are not a wall-clock window. Blank FOA units on the
        # day-based rows are minutes, which is the AutoSched default.
        if row["MTBPMUNITS"].strip().lower() in {"piece", "pieces"}:
            continue
        foa_units = linked["FOAUNITS"].strip() or "min"
        calendar.append(
            PmRow(
                cal_name=row["PMCALNAME"].strip(),
                family=linked["RESNAME"].strip(),
                first_start_sec=_to_sec(float(linked["FOA"]), foa_units),
                interval_sec=_to_sec(float(row["MTBPM"]), row["MTBPMUNITS"]),
                duration_sec=_to_sec(float(row["MTTR"]), row["MTTRUNITS"]),
            )
        )
    return calendar


def _scanners(path: Path) -> dict[str, int]:
    """Published STNQTY for expose families. Track, metrology, and rework stay out."""
    counts: dict[str, int] = {}
    for row in _rows(path):
        family = row["STNFAM"].strip()
        if not _is_scanner(family):
            continue
        counts[family] = int(float(row["STNQTY"]))
    return counts


def _is_scanner(family: str) -> bool:
    if not family.startswith("Litho_"):
        return False
    blocked = ("Track", "Met", "REG")
    return not any(token in family for token in blocked)


def _cycle_sec(step: dict[str, str]) -> float:
    minutes = float(step["PTIME"])
    if step["PTPER"].strip() == "per_piece":
        minutes *= PIECES
    return _to_sec(minutes, step["PTUNITS"] or "min")


def _to_sec(value: float, units: str) -> float:
    unit = units.strip().lower()
    if unit in {"min", "minute", "minutes"}:
        return value * 60.0
    if unit in {"hr", "hour", "hours"}:
        return value * 3600.0
    if unit in {"day", "days"}:
        return value * 86400.0
    if unit in {"sec", "s", "second", "seconds"}:
        return value
    raise ValueError(f"Unknown unit {units!r}")


def _stamp(text: str) -> datetime:
    return datetime.strptime(text.strip(), "%m/%d/%y %H:%M:%S").replace(tzinfo=UTC)


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _ts(moment: datetime) -> str:
    return _q(moment.strftime("%Y-%m-%d %H:%M:%S+00"))


def _num(value: float | None) -> str:
    if value is None:
        return "NULL"
    return repr(value)


def _create_operations() -> str:
    return """CREATE TABLE resilimes.operations (
  op_id TEXT PRIMARY KEY,
  recipe_id TEXT,
  station_group_id TEXT NOT NULL,
  std_cycle_time DOUBLE PRECISION NOT NULL,
  max_ped_sec DOUBLE PRECISION,
  requires_batch BOOLEAN NOT NULL,
  batch_size INTEGER,
  ped_target_op_id TEXT,
  provenance TEXT NOT NULL
);"""


def _insert_operations(rows: list[OperationRow]) -> list[str]:
    return [
        "INSERT INTO resilimes.operations (op_id, recipe_id, station_group_id, std_cycle_time, "
        "max_ped_sec, requires_batch, batch_size, ped_target_op_id, provenance) VALUES ("
        f"{_q(row.op_id)}, {_q(row.recipe_id)}, {_q(row.station_group_id)}, "
        f"{_num(row.std_cycle_time)}, {_num(row.max_ped_sec)}, "
        f"{'TRUE' if row.requires_batch else 'FALSE'}, "
        f"{'NULL' if row.batch_size is None else row.batch_size}, "
        f"{_q(row.ped_target_op_id) if row.ped_target_op_id else 'NULL'}, {_q('smt2020')});"
        for row in rows
    ]


def _create_setup() -> str:
    return """CREATE TABLE resilimes.setup_matrix (
  station_group_id TEXT NOT NULL,
  from_recipe TEXT NOT NULL,
  to_recipe TEXT NOT NULL,
  setup_time_sec DOUBLE PRECISION NOT NULL,
  provenance TEXT NOT NULL,
  PRIMARY KEY (station_group_id, from_recipe, to_recipe)
);"""


def _insert_setups(rows: list[SetupRow]) -> list[str]:
    return [
        "INSERT INTO resilimes.setup_matrix (station_group_id, from_recipe, to_recipe, "
        f"setup_time_sec, provenance) VALUES ({_q(row.station_group_id)}, {_q(row.from_recipe)}, "
        f"{_q(row.to_recipe)}, {_num(row.setup_time_sec)}, {_q('smt2020')});"
        for row in rows
    ]


def _create_orders() -> str:
    return """CREATE TABLE resilimes.orders (
  order_id TEXT PRIMARY KEY,
  customer TEXT NOT NULL,
  product_id TEXT NOT NULL,
  qty INTEGER NOT NULL,
  contract_due TIMESTAMPTZ NOT NULL,
  order_class TEXT NOT NULL,
  margin_tier TEXT NOT NULL,
  release_interval_min DOUBLE PRECISION NOT NULL,
  provenance TEXT NOT NULL
);"""


def _insert_orders(rows: list[OrderRow]) -> list[str]:
    return [
        "INSERT INTO resilimes.orders (order_id, customer, product_id, qty, contract_due, "
        "order_class, margin_tier, release_interval_min, provenance) VALUES ("
        f"{_q(row.order_id)}, {_q(row.customer)}, {_q(row.product_id)}, {row.qty}, "
        f"{_ts(row.contract_due)}, {_q(row.order_class)}, {_q(row.margin_tier)}, "
        f"{_num(row.release_interval_min)}, {_q(_PROVENANCE)});"
        for row in rows
    ]


def _create_lots() -> str:
    return """CREATE TABLE resilimes.lots (
  lot_id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL,
  current_op_id TEXT NOT NULL,
  priority_level INTEGER NOT NULL,
  arrival_time TIMESTAMPTZ NOT NULL,
  due_date TIMESTAMPTZ NOT NULL,
  ped_remaining_sec DOUBLE PRECISION,
  dpi DOUBLE PRECISION NOT NULL,
  dpi_updated_at TIMESTAMPTZ NOT NULL,
  late BOOLEAN NOT NULL,
  order_class TEXT NOT NULL,
  lot_value DOUBLE PRECISION NOT NULL,
  provenance TEXT NOT NULL
);"""


def _insert_lots(rows: list[LotRow]) -> list[str]:
    return [
        "INSERT INTO resilimes.lots (lot_id, product_id, current_op_id, priority_level, "
        "arrival_time, due_date, ped_remaining_sec, dpi, dpi_updated_at, late, order_class, "
        "lot_value, provenance) VALUES ("
        f"{_q(row.lot_id)}, {_q(row.product_id)}, {_q(row.current_op_id)}, {row.priority_level}, "
        f"{_ts(row.arrival_time)}, {_ts(row.due_date)}, NULL, {_num(row.dpi)}, "
        f"{_ts(row.dpi_updated_at)}, {'TRUE' if row.late else 'FALSE'}, {_q(row.order_class)}, "
        f"{_num(row.lot_value)}, {_q(_PROVENANCE)});"
        for row in rows
    ]


def _create_pm() -> str:
    return """CREATE TABLE resilimes.pm_calendar (
  cal_name TEXT PRIMARY KEY,
  family TEXT NOT NULL,
  first_start_sec DOUBLE PRECISION NOT NULL,
  interval_sec DOUBLE PRECISION NOT NULL,
  duration_sec DOUBLE PRECISION NOT NULL,
  provenance TEXT NOT NULL
);"""


def write_sql(source: Path, destination: Path) -> KernelTables:
    tables = load_tables(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render_sql(tables), encoding="utf-8")
    return tables


def _insert_pm(rows: list[PmRow]) -> list[str]:
    note = "smt2020 pmcal MTTR mean and attach FOA; not a random draw"
    return [
        "INSERT INTO resilimes.pm_calendar (cal_name, family, first_start_sec, interval_sec, "
        f"duration_sec, provenance) VALUES ({_q(row.cal_name)}, {_q(row.family)}, "
        f"{_num(row.first_start_sec)}, {_num(row.interval_sec)}, {_num(row.duration_sec)}, "
        f"{_q(note)});"
        for row in rows
    ]


